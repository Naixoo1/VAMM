import { describe, expect, it, vi } from "vitest";
import { runResearch } from "@/lib/ai/research";

// Audit regression: every provider response below is fabricated by this test.
// No external model, live company data, or trading service is called.
const request = {
  instrumentIds: ["edu-equity"],
  question: "Explain only the selected synthetic basket using its supplied evidence.",
};

const unsupportedClaims = [
  {
    label: "a fabricated live company valuation",
    summary: "Apple's current valuation is known.",
    fact: "Apple's live P/E is exactly 17 as of this minute.",
  },
  {
    label: "personalized buy/sell advice and guaranteed returns",
    summary: "Buy AAPL today and sell your other holdings.",
    fact: "Buying AAPL now guarantees a 20% profit for your portfolio.",
  },
  {
    label: "an invented synthetic return using an existing evidence ID",
    summary: "The selected synthetic equity basket returned 99%.",
    fact: "The selected equity basket has a cumulative modeled return of 99% over the authored three-year period.",
  },
];

describe("audit: semantic support of cited model facts", () => {
  it.each(unsupportedClaims)("rejects $label despite a valid-shaped citation", async ({ summary, fact }) => {
    const provider = vi.fn().mockResolvedValue({
      summary,
      facts: [{ text: fact, evidenceIds: ["ev-demo-method"] }],
      limitations: ["This text was generated by an adversarial audit stub."],
    });

    const result = await runResearch(request, provider);

    expect(provider).toHaveBeenCalledOnce();
    expect(result).toMatchObject({ ok: true, data: { origin: "prewritten" } });
    if (result.ok) {
      expect(result.data.summary).not.toBe(summary);
      expect(result.data.facts.map(item => item.text)).not.toContain(fact);
    }
  });
});
